#!/usr/bin/env bash
# One-time setup. Safe to re-run; it only overwrites what it generates.
#
#   scripts/setup.sh
#
# 1. Provisions the runtime's own toolchain (Python 3.14, uv, Node, Chromium) into
#    .groupcart-home/tools. First run downloads about 2 GB and takes a few minutes.
# 2. Writes .groupcart-home/config.yaml and SOUL.md from app/runtime/.
# 3. Copies the secrets from .env into the runtime's own .env, under the names it expects.
# 4. Links our plugins (app/split, vault/cardvault) into the runtime.
# 5. Installs the Photon sidecar's Node dependencies.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export GROUPCART_HOME="${GROUPCART_HOME:-$ROOT/.groupcart-home}"
export GROUPCART_RUNTIME_DIR="${GROUPCART_RUNTIME_DIR:-$GROUPCART_HOME/tools}"
RUN="$ROOT/core/scripts/run-in-groupcart-env"

[ -f "$ROOT/.env" ] || { echo "Missing $ROOT/.env — copy .env.example and fill it in."; exit 1; }
set -a
# shellcheck disable=SC1091
. "$ROOT/.env"
set +a

echo "==> Provisioning the runtime (first run is slow)"
mkdir -p "$GROUPCART_HOME/plugins"
"$RUN" true

echo "==> Writing runtime config and persona"
cp "$ROOT/app/runtime/config.yaml" "$GROUPCART_HOME/config.yaml"
cp "$ROOT/app/runtime/SOUL.md" "$GROUPCART_HOME/SOUL.md"

echo "==> Writing runtime secrets"
IFS=',' read -r -a GEMINI_KEYS <<< "${GEMINI_API_KEYS:-${GEMINI_API_KEY:-}}"
umask 077
{
    echo "# Generated by scripts/setup.sh from the repo-root .env. Edit that file, then re-run setup."
    echo "PHOTON_PROJECT_ID=${PHOTON_PROJECT_ID:-${SPECTRUM_PROJECT_ID:-}}"
    echo "PHOTON_PROJECT_SECRET=${PHOTON_PROJECT_SECRET:-${SPECTRUM_PROJECT_SECRET:-}}"
    # Friends text in from their own numbers; without this only paired numbers get an answer.
    echo "PHOTON_ALLOW_ALL_USERS=${PHOTON_ALLOW_ALL_USERS:-true}"
    # The first two Gemini keys form a rotation pool on their own; add more with
    #   ./gc auth add gemini --type api-key --api-key <key>
    echo "GEMINI_API_KEY=${GEMINI_KEYS[0]:-}"
    [ -n "${GEMINI_KEYS[1]:-}" ] && echo "GOOGLE_API_KEY=${GEMINI_KEYS[1]}"
    echo "NESSIE_API_KEY=${NESSIE_API_KEY:-}"
} > "$GROUPCART_HOME/.env"
chmod 600 "$GROUPCART_HOME/.env"

echo "==> Linking plugins"
ln -sfn "$ROOT/app/split" "$GROUPCART_HOME/plugins/split"
ln -sfn "$ROOT/vault/cardvault" "$GROUPCART_HOME/plugins/cardvault"

echo "==> Installing the Photon sidecar"
"$RUN" npm ci --prefix "$ROOT/core/plugins/platforms/photon/sidecar" --no-audit --no-fund

echo
echo "Done. Next:"
echo "  ./gc gateway run            # start the iMessage agent"
echo "  scripts/demo_cli.sh         # run the whole dinner split in the terminal, no phones"
echo "  ./gc split room --watch     # watch the agents talk to each other"
